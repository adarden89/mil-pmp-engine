"use client";

import { motion } from "framer-motion";
import { FileDown, Languages, ShieldCheck, TriangleAlert, UserCheck } from "lucide-react";
import { useMemo, useState } from "react";
import { CopyButton } from "@/components/ui/copy-button";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { analyzeAuditDensity } from "@/lib/audit-density";
import { LEGAL_DISCLAIMER } from "@/lib/site";
import {
  PROCESS_GROUP_LABELS,
  type ProcessGroupKey,
  type TranslateRequest,
  type TranslationResult,
} from "@/lib/translation-schema";
import { AuditDensityMeter } from "./audit-density-meter";

const GROUP_ORDER: ProcessGroupKey[] = ["initiating", "planning", "executing", "monitoringControlling", "closing"];

function plainTextExport(result: TranslationResult): string {
  return [
    result.civilianProjectTitle,
    "",
    result.applicationSummary,
    "",
    `Objective: ${result.objective}`,
    `Role: ${result.role}`,
    `Outcome: ${result.outcome}`,
    `Deliverables: ${result.deliverables.join("; ")}`,
  ].join("\n");
}

async function exportPdf(result: TranslationResult, input: TranslateRequest | null) {
  // Loaded on demand so jsPDF never weighs down the initial page.
  const { PdfBuilder } = await import("@/lib/documents/pdf-builder");
  const report = analyzeAuditDensity(result);
  const pdf = new PdfBuilder(
    `Generated by MilToPMP Enterprise. Verify every statement with your supervisor before submitting to PMI. ${LEGAL_DISCLAIMER}`,
  )
    .header(
      result.civilianProjectTitle,
      input ? `${input.rateOrMos} · ${input.startMonth} to ${input.endMonth}` : "PMI project experience",
    )
    .section(`Application summary (${report.wordCount} words · ${report.gradeLabel.toLowerCase()})`)
    .paragraph(result.applicationSummary)
    .section("Project details")
    .labeled("Objective", result.objective)
    .labeled("Role", result.role)
    .labeled("Outcome", result.outcome)
    .section("Deliverables")
    .bullets(result.deliverables);
  for (const key of GROUP_ORDER) {
    if (result.processGroups[key].length > 0) {
      pdf.section(PROCESS_GROUP_LABELS[key]).bullets(result.processGroups[key]);
    }
  }
  if (result.auditFlags.length > 0) pdf.section("Verify before submitting").checklist(result.auditFlags);
  pdf.section("Suggested verifier").paragraph(result.suggestedVerifier);
  const slug = result.civilianProjectTitle
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 60);
  pdf.save(`pmi-experience-${slug || "project"}.pdf`);
}

export function TranslationResultView({
  result,
  input,
  isSample = false,
}: {
  result: TranslationResult;
  input: TranslateRequest | null;
  isSample?: boolean;
}) {
  const report = useMemo(() => analyzeAuditDensity(result), [result]);
  const [exporting, setExporting] = useState(false);

  return (
    <motion.div
      initial={{ opacity: 0, y: 16 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.45 }}
      className="space-y-6"
    >
      {isSample ? (
        <p className="rounded-lg border border-brass/30 bg-brass/10 px-4 py-2.5 text-sm text-brass">
          Sample output from example evaluation bullets. Your own translation uses only the facts you provide.
        </p>
      ) : null}

      <div className="grid gap-6 lg:grid-cols-[1.6fr_1fr]">
        <Card className="p-6 sm:p-8">
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <p className="font-mono text-xs tracking-widest text-subtle uppercase">PMI application text</p>
              <h3 className="mt-1 text-xl font-semibold">{result.civilianProjectTitle}</h3>
            </div>
            <div className="flex flex-wrap gap-2">
              <CopyButton text={result.applicationSummary} label="Copy summary" />
              <CopyButton text={plainTextExport(result)} label="Copy all" />
              <Button
                size="sm"
                variant="secondary"
                loading={exporting}
                onClick={async () => {
                  setExporting(true);
                  try {
                    await exportPdf(result, input);
                  } finally {
                    setExporting(false);
                  }
                }}
                icon={<FileDown className="size-4" aria-hidden />}
              >
                Export PDF
              </Button>
            </div>
          </div>
          <p className="mt-6 text-[15px] leading-7 whitespace-pre-line">{result.applicationSummary}</p>
          <p className="mt-4 font-mono text-xs text-subtle">{report.wordCount} words · PMI recommends 200 to 500</p>
        </Card>

        <Card className="p-6">
          <p className="mb-5 flex items-center gap-2 font-mono text-xs tracking-widest text-subtle uppercase">
            <ShieldCheck className="size-3.5" aria-hidden /> Audit risk meter
          </p>
          <AuditDensityMeter report={report} />
        </Card>
      </div>

      <div className="grid gap-6 md:grid-cols-3">
        {[
          { label: "Objective", value: result.objective },
          { label: "Your role", value: result.role },
          { label: "Outcome", value: result.outcome },
        ].map((item) => (
          <Card key={item.label} className="p-5">
            <div className="flex items-center justify-between">
              <p className="font-mono text-xs tracking-widest text-subtle uppercase">{item.label}</p>
              <CopyButton text={item.value} />
            </div>
            <p className="mt-3 text-sm leading-relaxed">{item.value}</p>
          </Card>
        ))}
      </div>

      <Card className="p-6 sm:p-8">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <p className="font-mono text-xs tracking-widest text-subtle uppercase">Lifecycle evidence by process group</p>
          <CopyButton
            label="Copy all groups"
            text={GROUP_ORDER.map(
              (key) =>
                `${PROCESS_GROUP_LABELS[key]}:\n${result.processGroups[key].map((item) => `- ${item}`).join("\n") || "- (no evidence)"}`,
            ).join("\n\n")}
          />
        </div>
        <div className="mt-6 grid gap-4 md:grid-cols-5">
          {GROUP_ORDER.map((key, index) => {
            const items = result.processGroups[key];
            return (
              <div key={key} className="rounded-xl border border-border bg-bg-elevated/60 p-4">
                <div className="flex items-center gap-2">
                  <span className="grid size-6 place-items-center rounded-full bg-brand/10 font-mono text-[11px] text-brand">
                    {index + 1}
                  </span>
                  <p className="text-sm font-semibold">{PROCESS_GROUP_LABELS[key]}</p>
                </div>
                {items.length > 0 ? (
                  <ul className="mt-3 space-y-2">
                    {items.map((item) => (
                      <li key={item} className="text-xs leading-relaxed text-muted-foreground">
                        {item}
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p className="mt-3 text-xs text-danger">No evidence in your bullets.</p>
                )}
              </div>
            );
          })}
        </div>
      </Card>

      <div className="grid gap-6 lg:grid-cols-2">
        <Card className="border-warning/25 p-6">
          <p className="flex items-center gap-2 font-mono text-xs tracking-widest text-warning uppercase">
            <TriangleAlert className="size-3.5" aria-hidden /> Verify before you submit
          </p>
          {result.auditFlags.length > 0 ? (
            <ul className="mt-4 space-y-2.5">
              {result.auditFlags.map((flag) => (
                <li key={flag} className="flex gap-2.5 text-sm">
                  <span className="mt-1.5 size-1.5 shrink-0 rounded-full bg-warning" aria-hidden />
                  {flag}
                </li>
              ))}
            </ul>
          ) : (
            <p className="mt-4 text-sm text-muted-foreground">No open items flagged.</p>
          )}
          <div className="mt-6 flex items-start gap-2.5 rounded-lg border border-border bg-bg-elevated/60 p-3">
            <UserCheck className="mt-0.5 size-4 shrink-0 text-brand" aria-hidden />
            <div>
              <p className="text-xs font-medium">Suggested verifier</p>
              <p className="text-xs text-muted-foreground">{result.suggestedVerifier}</p>
            </div>
          </div>
        </Card>

        <Card className="p-6">
          <p className="flex items-center gap-2 font-mono text-xs tracking-widest text-subtle uppercase">
            <Languages className="size-3.5" aria-hidden /> Jargon translated
          </p>
          <div className="mt-4 max-h-72 overflow-auto">
            <table className="w-full text-left text-sm">
              <thead className="sticky top-0 bg-surface text-xs text-subtle">
                <tr>
                  <th className="py-2 pr-4 font-medium">Military</th>
                  <th className="py-2 font-medium">Civilian</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-border">
                {result.jargonTranslations.map((row) => (
                  <tr key={row.military}>
                    <td className="py-2 pr-4 font-mono text-xs text-muted-foreground">{row.military}</td>
                    <td className="py-2 text-sm">{row.civilian}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="mt-4 flex flex-wrap gap-2">
            <Badge variant="neutral">{result.deliverables.length} deliverables</Badge>
            <Badge variant="neutral">{result.jargonTranslations.length} terms translated</Badge>
          </div>
        </Card>
      </div>
    </motion.div>
  );
}
